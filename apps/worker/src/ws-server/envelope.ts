// LiveEnvelope — 경로 A(WS 프론트 직결) 방송 메시지 봉투 (M2 경로 A Step 1, 2026-06-22).
//
// 설계 원칙 (사용자 결정 2026-06-22 — "불투명 토픽 + 자유 페이로드"):
//   - topic 은 **불투명 라우팅 키**. 운반층(LiveBus/WsServer)은 이 문자열을
//     절대 파싱·해석하지 않는다. "2번째 칸이 시장" 같은 규격을 코드 어디서도
//     강제하지 않음 — 의미는 데이터 소스(레지스트리, Step 3)가 소유.
//   - payload 는 **자유 형식(unknown)**. 운반층은 내용물을 들여다보지 않고,
//     소비자(프론트 카드)가 자기 datasource 의 Zod 스키마로 검증한다
//     (경로 C = AI 출력과 동일한 "엣지에서 검증" 패턴).
//   - 이 구조라야 추후 뉴스/온체인/타 거래소가 "토픽 짓는 법 + payload 스키마"
//     등록만으로 같은 파이프에 꽂힘 (운반 서버 코드 0줄 변경).
// ============================================================

/**
 * 프론트로 방송되는 한 건의 라이브 메시지.
 * 운반층은 topic/payload 둘 다 불투명하게 다룬다 (전달만).
 */
export interface LiveEnvelope {
  /** 불투명 라우팅 키 (소스가 정함, 운반층 미파싱). 예: "binance:ticker:futures_usdm:BTCUSDT" (Step 4 buildLiveTopic 형식). */
  topic: string;
  /** 방송 시각 (epoch ms). */
  ts: number;
  /** 서버 전역 단조 증가 시퀀스 — 전역 방송 순서 디버깅용(토픽별 연속성 아님). */
  seq: number;
  /** 자유 형식 페이로드 — 운반층은 안 들여다봄. 소비자가 Zod 로 검증. */
  payload: unknown;
}
